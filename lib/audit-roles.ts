/** Primary role as stored on the entry; a Super Admin counts as Admin. */
export function auditActorRole(user: { role: string; isSuperAdmin?: boolean | null }) {
  return user.isSuperAdmin ? 'ADMIN' : user.role
}

/**
 * The role a change was made as: the primary role when it covers the action, otherwise the
 * secondary role that does. Null when neither covers it (shouldn't happen — worth a look).
 */
export function actingRoleFor(action: string, primaryRole: string | null, secondaryRoles: readonly string[]) {
  const owners = AUDIT_ACTION_OWNERS[action]
  if (!owners || !primaryRole || owners.includes(primaryRole)) return primaryRole
  return secondaryRoles.find((role) => owners.includes(role)) ?? null
}

/** True when the actor's primary role is not one the action belongs to. */
export function isOutsidePrimaryRole(action: string, actorRole: string | null | undefined) {
  const owners = AUDIT_ACTION_OWNERS[action]
  return Boolean(owners && actorRole && !owners.includes(actorRole))
}
